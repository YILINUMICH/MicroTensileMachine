"""operator_noise_isense.py — where does the A1 current-sense noise come from?

WHY THIS EXISTS
---------------
The CC loop on the H7 overshoots by up to 50% while the SAME control law on an
Uno, driving the SAME board (INA296A gain 10, 0.2 ohm shunt), holds target to
0.1%. The control law was diffed line for line first and is a faithful port, so
the difference had to be the measurement.

WHAT THE MEASUREMENTS ACTUALLY SAID (2026-07-28, five captures)

    SMA disconnected, voltage   0.4 mA mean   12.10 mA sd   24.2 mA/read
    connected, voltage          106 mA        14.44 mA      28.9 mA/read
    connected, cc 106           112 mA        15.11 mA      30.2 mA/read
    connected, cc 155           161 mA        15.60 mA      31.2 mA/read
    connected, cc 100           108 mA        14.73 mA      29.5 mA/read
    Uno reference               180 mA         0.90 mA       2.55 mA/read

The H7 front end is ~12x the Uno, flat in current and identical in CC vs voltage
mode. An earlier version of this file claimed 144 mA/read, 5981x the
quantisation floor, 57x the Uno, and "cannot be fixed in the control code" —
ALL WRONG. That figure came from the sweep's cool phase, whose distribution is
multimodal rather than Gaussian (see data/raw/sweep_20260728_215606/README.md), and
I generalised a contaminated condition to the hardware. The correction matters:
at 15.6 mA sd, ADC_SAMPLES_CYCLE=64 gives 3.9 mA at 383 Hz — 3-sigma inside the
gate and twice the Uno's rate. Averaging IS a viable fix.

The noise still breaks the controller in two places, both deciding on ONE
sample: the `near` gate (12 mA band at the 100 mA cool target) and the bootstrap
latch of R_est = u/I, where a low sample gives 0.5/0.08 = 6.25 ohm — exactly the
wrong value the loop gets stranded on.

WHAT THIS TEST DECIDES
----------------------
Whether the noise is generated by the H7's own analog front end, or picked up
from the switched load. The two need opposite fixes, so guessing is expensive.

    A  sma-disconnected   MOSFET on, LDO on, ZERO current
    B  sma-connected      same command, ~155 mA flowing
    C  sma-higher         higher command, ~240 mA flowing

    A ~= B ~= C          -> the H7 ADC path itself. Fix = ADC sampling-time
                            config + an RC on the INA output before A1.
    A quiet, B/C noisy   -> pickup from the load/switching. Fix = filtering,
                            shielding, grounding, routing.
    noise scales with I  -> proportional pickup or genuine LDO ripple.

Voltage mode (`cycle`) is used deliberately: the DAC command is CONSTANT for
the whole capture, so anything that moves is measurement, not control. Note the
open-load fault is inside `if (cc_enabled)` in the firmware, so voltage mode
will happily run with the SMA disconnected — CC mode would disarm itself.

USAGE
-----
Run each condition, physically changing the rig between them:

    python operator_noise_isense.py --port COM8 --label sma-disconnected --volts 0.5
    python operator_noise_isense.py --port COM8 --label sma-connected    --volts 0.5
    python operator_noise_isense.py --port COM8 --label sma-higher       --volts 1.0

    python operator_noise_isense.py --compare data/raw/isense_*

The laser (src=1, on the ADS1263 — a different converter entirely) is recorded
throughout as a CONTROL. If it changes between conditions, the rig's ambient
state changed and the comparison is not clean. This is the same discipline that
caught the invalid floating-input attempt in the load-cell noise work.
"""
from __future__ import annotations

import argparse
import glob
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from lib_h7_session import (H7, SRC_LASER, SRC_SMA_V, SRC_SMA_I,  # noqa: E402
                            save_capture)

RAW = Path(__file__).resolve().parent.parent / "data" / "raw"

# Firmware constants — Firmware_SMAConstantCurrent_PIO/src/main.cpp.
# If any of these change there, they must change here.
ADC_RES_MAX = (1 << 16) - 1
ADC_VREF_V = 3.145
INA_GAIN = 10.0
R_SHUNT_OHM = 0.2
N_AVG_CYCLE = 4                       # ADC_SAMPLES_CYCLE
I_PER_LSB_MA = 1e3 * (ADC_VREF_V / ADC_RES_MAX) / (INA_GAIN * R_SHUNT_OHM)

BANDS = [(0, 1), (1, 10), (10, 50), (50, 120), (120, 250), (250, 490)]


def paired(cap):
    """src=3 and src=4 are emitted by the same streamSma() call, so they share
    hw_us exactly. Pair on it — a resampled join would invent correlation."""
    v, i = {}, {}
    for s in cap.samples:
        if s.src == SRC_SMA_V:
            v[s.hw_us] = s.value
        elif s.src == SRC_SMA_I:
            i[s.hw_us] = s.value
    k = sorted(set(v) & set(i))
    return (np.array(k, float) * 1e-6,
            np.array([v[x] for x in k]),
            np.array([i[x] for x in k]))


def analyse(cap, label):
    t, V, I = paired(cap)
    if len(t) < 500:
        print(f"  !! only {len(t)} paired V/I samples — capture failed")
        return None
    fs = len(t) / (t[-1] - t[0])
    I_mA = 1e3 * I

    # Detrend: at a non-zero current the wire heats and R drifts during the
    # capture. That drift is real plant behaviour, not noise — leaving it in
    # would inflate sd and make higher currents look noisier than they are.
    dt = lambda y: y - np.polyval(np.polyfit(t, y, 1), t)
    Id, Vd = dt(I_mA), dt(V)

    per_sample = Id.std() * np.sqrt(N_AVG_CYCLE)
    out = {
        "label": label, "n": len(t), "fs": fs,
        "I_mean": I_mA.mean(), "I_sd": Id.std(),
        "V_mean": V.mean(), "V_sd": 1e3 * Vd.std(),
        "per_sample_mA": per_sample, "lsb": per_sample / I_PER_LSB_MA,
        "corr": float(np.corrcoef(Vd, Id)[0, 1]),
    }

    print(f"\n  {label}")
    print(f"    {len(t)} paired samples, {fs:.0f} Hz, {t[-1]-t[0]:.1f} s")
    print(f"    I  mean {I_mA.mean():8.2f} mA   sd {Id.std():7.2f} mA")
    print(f"    V  mean {V.mean():8.4f} V    sd {1e3*Vd.std():7.2f} mV")
    print(f"    per single ADC reading  {per_sample:7.2f} mA  = {per_sample/I_PER_LSB_MA:7.0f} LSB")
    print(f"      (Uno reference: 2.55 mA = 1.04 LSB of ITS converter)")
    print(f"    corr(V, I) = {out['corr']:+.4f}   "
          f"[+1 = real current ripple, 0 = independent channel noise]")

    las = np.array([s.value for s in cap.samples if s.src == SRC_LASER])
    if len(las) > 100:
        out["laser_sd_mV"] = 1e3 * (las - las.mean()).std()
        print(f"    laser CONTROL (src=1, ADS1263): sd {out['laser_sd_mV']:.3f} mV")

    try:
        from scipy import signal
        g = np.linspace(t[0], t[-1], len(t))
        f, p = signal.welch(np.interp(g, t, Id), fs=fs, nperseg=1024,
                            detrend="linear")
        tot = np.trapezoid(p, f)
        out["bands"] = {}
        print(f"    spectrum:")
        for lo, hi in BANDS:
            m = (f >= lo) & (f < hi)
            if m.sum() < 2:
                continue
            r = np.sqrt(np.trapezoid(p[m], f[m]))
            out["bands"][f"{lo}-{hi}"] = r
            print(f"      {lo:4.0f}-{hi:4.0f} Hz  {r:7.2f} mA  "
                  f"{100*np.trapezoid(p[m], f[m])/tot:5.1f}%")
    except ImportError:
        print("    (scipy missing — no spectrum)")
    return out


def capture(args):
    banner = {
        "sma-disconnected": "SMA MUST BE DISCONNECTED (open circuit at the clips)",
        "sma-connected": "SMA connected and preloaded as normal",
        "sma-higher": "SMA connected and preloaded as normal",
    }.get(args.label, "check the rig matches the label you chose")
    drive = {
        "voltage": f"{args.volts:.3f} V static command, no CC loop",
        "cc": f"cc {args.ma:.0f} mA, loop closed, DAC written every tick",
        "cccycle": (f"cccycle {args.ma_high:.0f}/{args.ma:.0f} mA, 100 ms heat "
                    f"/ 12 s cool — reproduces the sweep"),
    }[args.mode]
    print(f"\nisense noise test — condition '{args.label}' / mode '{args.mode}'")
    print(f"  {banner}")
    print(f"  {drive}, {args.secs:.0f} s\n")
    if input("  type GO to start: ").strip() != "GO":
        sys.exit("aborted")

    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    out = Path(args.outdir) / f"isense_{stamp}_{args.label}-{args.mode}"
    h7 = H7(args.port)
    h7.open()
    try:
        h7.send("arm")
        time.sleep(0.5)
        if args.mode == "cccycle":
            # Reproduce the ACTUAL failing condition. `cc` cannot: when R_est
            # bootstraps correctly the loop lands near target and the gate opens
            # (measured 2026-07-28: cc 100 -> 108.4 mA, err 8.4 < 12 mA band,
            # 14.7 mA sd, clean). The sweep's cool phase only goes bad when
            # R_est latches WRONG at cccycle start, which strands the loop 55%
            # above target with the gate shut. That latch is a dice roll on one
            # ADC sample, so it has to be reproduced, not commanded.
            h7.send(f"cccycle {args.ma_high:.1f} {args.ma:.1f} 100 12000 "
                    f"{max(1, int(args.secs // 12.1))}")
        elif args.mode == "cc":
            # CC mode writes the MCP4728 over I2C EVERY control tick. Voltage
            # mode holds the DAC static. Comparing the two AT THE SAME CURRENT
            # is what isolates the per-tick DAC write as a noise source —
            # measured 2026-07-28: 144.4 mA/read under CC at 155 mA vs
            # 28.9 mA/read in voltage mode at 106 mA, but those two differ in
            # current as well as mode, so the comparison was not clean.
            h7.send(f"cc {args.ma:.1f} {int(args.secs * 1000)}")
        else:
            # v_high == v_idle -> the command never moves for the whole capture.
            half = int(args.secs * 1000 / 2)
            h7.send(f"cycle {args.volts:.4f} {args.volts:.4f} {half} {half} 1")
        print(f"  capturing {args.secs:.0f} s ...")
        cap = h7.capture(args.secs + 1.0,
                         on_console=lambda t, s: print(f"    [{t:6.2f}] {s}")
                         if ("FAULT" in s or "DISARM" in s) else None)
    finally:
        h7.disarm()
        h7.close()

    save_capture(cap, out / "h7.csv", {
        "label": args.label, "mode": args.mode, "volts": args.volts,
        "ma": args.ma, "secs": args.secs,
        "port": args.port, "n_avg": N_AVG_CYCLE,
        "captured_utc": datetime.now(timezone.utc).isoformat(),
    })
    analyse(cap, args.label)
    print(f"\n  -> {out}")
    print(f"  run the other conditions, then: "
          f"python operator_noise_isense.py --compare {args.outdir}/isense_*")


def compare(dirs):
    import csv
    from lib_h7_session import Capture, Sample
    res = []
    for d in dirs:
        p = Path(d) / "h7.csv"
        if not p.exists():
            print(f"  skip {d} (no h7.csv)")
            continue
        cap = Capture()
        for r in csv.DictReader(open(p)):
            cap.samples.append(Sample(int(r["src"]), int(r["hw_us"]),
                                      float(r["value"]), int(r["raw_code"]),
                                      int(r["seq"])))
        got = analyse(cap, Path(d).name.split("_", 2)[-1])
        if got:
            res.append(got)

    if len(res) < 2:
        return
    print("\n" + "=" * 72)
    print(f"{'condition':<20}{'I mean':>10}{'I sd':>10}{'per-sample':>12}{'LSB':>9}{'laser':>9}")
    for r in res:
        print(f"{r['label']:<20}{r['I_mean']:9.1f} {r['I_sd']:9.2f} "
              f"{r['per_sample_mA']:11.2f} {r['lsb']:8.0f} "
              f"{r.get('laser_sd_mV', float('nan')):8.3f}")

    zero = [r for r in res if "disconnect" in r["label"]]
    live = [r for r in res if "disconnect" not in r["label"]]
    print("\nVERDICT")
    if not zero or not live:
        print("  need both a disconnected and a connected condition to decide.")
        return
    z = zero[0]["per_sample_mA"]
    l = max(r["per_sample_mA"] for r in live)
    print(f"  zero-current  {z:7.2f} mA/sample")
    print(f"  with current  {l:7.2f} mA/sample     ratio {l/max(z,1e-9):.2f}x")
    if z > 20:
        print("  -> The noise is ALREADY THERE at zero current: it is the H7's own\n"
              "     analog front end, not the load. Fix the ADC sampling-time\n"
              "     config and add an RC on the INA output before A1.")
    elif l / max(z, 1e-9) > 3:
        print("  -> Quiet at zero current, noisy under load: the noise arrives WITH\n"
              "     the load current. Fix filtering / shielding / grounding /\n"
              "     routing on the shunt-to-INA-to-A1 path.")
    else:
        print("  -> Neither pattern is clean. Check the laser control column: if it\n"
              "     also moved, the rig's ambient state changed between captures and\n"
              "     the comparison is not valid — re-run them back to back.")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--port", default="COM8")
    ap.add_argument("--secs", type=float, default=20.0)
    ap.add_argument("--volts", type=float, default=0.5,
                    help="static LDO command; 0.5 = the idle floor (~155 mA)")
    ap.add_argument("--label", default="sma-connected",
                    choices=["sma-disconnected", "sma-connected", "sma-higher"])
    ap.add_argument("--mode", default="voltage",
                    choices=["voltage", "cc", "cccycle"],
                    help="voltage = DAC held static; cc = DAC written every "
                         "control tick. Compare AT THE SAME CURRENT to isolate "
                         "the per-tick I2C DAC write as a noise source.")
    ap.add_argument("--ma", type=float, default=106.0,
                    help="target current for --mode cc; for --mode cccycle this "
                         "is i_low (the cool target). Match the voltage-mode "
                         "capture's MEASURED mean so only the mode differs.")
    ap.add_argument("--ma-high", type=float, default=550.0,
                    help="--mode cccycle only: the heat target, i.e. the sweep "
                         "level being reproduced")
    ap.add_argument("--outdir", default=str(RAW))
    ap.add_argument("--compare", nargs="+", metavar="DIR")
    args = ap.parse_args()

    if args.compare:
        dirs = [d for pat in args.compare for d in sorted(glob.glob(pat))] \
            or args.compare
        compare(dirs)
    else:
        capture(args)


if __name__ == "__main__":
    main()
