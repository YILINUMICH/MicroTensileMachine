"""CAPTURE INVENTORY -> data/raw/INDEX.md.  Regenerate after every run.

    python make_index.py            # rewrite data/raw/INDEX.md
    python make_index.py --check    # exit 1 if the file is stale (CI / pre-commit)

data/raw/README.md documents the capture FORMAT — how to read one folder. This
writes the other half: WHICH folder to read. Folder names carry a timestamp and
nothing else, so with 20 sweeps on disk the only way to find the 10 mm-wire
500 ms run was to open meta.json files one at a time.

Everything here is DERIVED FROM THE FILES, never hand-maintained: the grid comes
off the capture filenames, the protocol off meta.json, the campaign off the
folder's parent, and registration off CAMPAIGNS in analyze_raw.py. A stale index
is therefore a bug in this script, not a chore you forgot.

═══ WHAT IT FLAGS ═════════════════════════════════════════════════════════
  unfiled      a sweep sitting loose in data/raw/ rather than under
               campaigns/<key>/. data/raw/ is an INBOX; a run left there has
               no recorded wire, because meta.json does not carry one.
  old naming   captures named `level_850mA_h400ms.csv` instead of
               `c23_level_...`. Every glob in the pipeline matches `c*_level_*`,
               so these folders are INVISIBLE to analyze_raw / get_cycle /
               plot_drive_trajectory — present on disk, absent from every
               table. Reported, never hidden.
  unregistered a capture folder in no CAMPAIGNS entry, so stage 1 never reads
               it and no merged table contains it.
"""
import argparse
import collections
import glob
import json
import os
import re
import sys

from analyze_raw import CAMPAIGNS, RAW

_HERE = os.path.dirname(os.path.abspath(__file__))
INDEX = os.path.join(RAW, "INDEX.md")

# Matches BOTH capture-naming generations. The pipeline deliberately matches
# only the `cNN_` form; this script matches both so it can report the gap.
_NAME = re.compile(r"^(c\d+_)?level_([\d.]+)mA_h(\d+)ms\.csv$")
_STAMP = re.compile(r"(\d{8})_(\d{6})")

BUCKETS = ["campaigns", "writeups", "aborted", "troubleshoot"]


def du_mb(path):
    total = 0
    for root, _, files in os.walk(path):
        for f in files:
            try:
                total += os.path.getsize(os.path.join(root, f))
            except OSError:
                pass
    return total / 1e6


def describe(path):
    """Everything the FILES say about one capture folder."""
    caps = [os.path.basename(f) for f in glob.glob(os.path.join(path, "*level_*mA_h*ms.csv"))]
    grid = collections.defaultdict(set)
    n_new = 0
    for c in caps:
        m = _NAME.match(c)
        if not m:
            continue
        n_new += bool(m.group(1))
        grid[int(m.group(3))].add(float(m.group(2)))
    meta = {}
    for f in sorted(glob.glob(os.path.join(path, "*.meta.json"))):
        try:
            meta = json.load(open(f, encoding="utf-8"))
            break
        except Exception:
            continue
    levels = sorted({l for s in grid.values() for l in s})
    heats = sorted(grid)
    md = glob.glob(os.path.join(path, "*.md"))
    png = glob.glob(os.path.join(path, "*.png"))
    if caps:
        kind = "captures"
    elif md or png:
        kind = "write-up"
    else:
        kind = "aborted"
    return {
        "n": len(caps),
        "naming": ("cNN" if n_new == len(caps) else
                   "OLD" if n_new == 0 else "mixed") if caps else "—",
        "levels": levels, "heats": heats,
        "cool_s": meta.get("cool_s"), "cycles": meta.get("cycles"),
        "when": (meta.get("captured_utc") or "")[:10],
        "kind": kind, "mb": du_mb(path),
        "cycles_csv": os.path.exists(os.path.join(path, "cycles.csv")),
    }


def grid_str(d):
    if not d["levels"]:
        return "—"
    lv, hs = d["levels"], d["heats"]
    l = f"{min(lv):.0f}" if len(lv) == 1 else f"{min(lv):.0f}–{max(lv):.0f}"
    h = f"{min(hs)}" if len(hs) == 1 else f"{min(hs)}–{max(hs)}"
    return f"{l} mA × {h} ms ({len(lv)}×{len(hs)})"


def registered():
    """{bare folder name: campaign key} from CAMPAIGNS."""
    return {f: k for k, c in CAMPAIGNS.items() for f, *_ in c["runs"]}


def child_dirs(path):
    return sorted(d for d in os.listdir(path)
                  if os.path.isdir(os.path.join(path, d))) if os.path.isdir(path) else []


def build():
    reg = registered()
    L = ["# `data/raw/` — capture INDEX",
         "",
         "**Generated by `analysis/make_index.py` — do not hand-edit.** Re-run it "
         "after every capture. `README.md` in this folder documents the capture "
         "*format*; this file says *which folder to read*.",
         ""]

    # ---- campaigns ----------------------------------------------------
    L += ["## Campaigns", "",
          "One campaign = one **wire + protocol**. Cold length is the axis that "
          "matters most — it is the same Dynalloy stock throughout — so it is in "
          "every folder name. `registered` means the folder is listed in "
          "`CAMPAIGNS` in `analysis/analyze_raw.py` and therefore reaches the "
          "merged table; an unregistered folder is on disk but in no table.", ""]
    camp_root = os.path.join(RAW, "campaigns")
    for camp in child_dirs(camp_root):
        cpath = os.path.join(camp_root, camp)
        folders = child_dirs(cpath)
        keys = {reg[f] for f in folders if f in reg}
        merged = ", ".join(sorted(f"`{CAMPAIGNS[k]['merged']}`" for k in keys)) or "— *(none)*"
        tot = sum(du_mb(os.path.join(cpath, f)) for f in folders)
        L += [f"### `campaigns/{camp}/`", "",
              f"{len(folders)} folders · {tot/1000:.2f} GB · merged table: {merged}", "",
              "| folder | kind | captures | grid | cool | cycles | naming | registered |",
              "|---|---|---|---|---|---|---|---|"]
        for f in folders:
            d = describe(os.path.join(cpath, f))
            nm = d["naming"] if d["naming"] != "OLD" else "**OLD**"
            rg = f"`{reg[f]}`" if f in reg else "**no**"
            cool = f"{d['cool_s']:.0f} s" if d["cool_s"] is not None else "—"
            L.append(f"| `{f}` | {d['kind']} | {d['n']} | {grid_str(d)} | {cool} "
                     f"| {d['cycles'] if d['cycles'] is not None else '—'} | {nm} | {rg} |")
        L.append("")

    # ---- unfiled ------------------------------------------------------
    loose = [d for d in child_dirs(RAW) if d not in BUCKETS and d != "logs"]
    L += ["## Unfiled — loose in `data/raw/`", ""]
    if loose:
        L += ["`data/raw/` is an **inbox**. These runs record no wire (meta.json "
              "does not carry one), so file them under `campaigns/<key>/` while "
              "you still remember which wire was on the rig.", "",
              "| folder | kind | captures | grid | cool | naming |", "|---|---|---|---|---|---|"]
        for f in loose:
            d = describe(os.path.join(RAW, f))
            cool = f"{d['cool_s']:.0f} s" if d["cool_s"] is not None else "—"
            L.append(f"| `{f}` | {d['kind']} | {d['n']} | {grid_str(d)} | {cool} | {d['naming']} |")
    else:
        L.append("*None — every capture is filed under a campaign.*")
    L.append("")

    # ---- the other buckets --------------------------------------------
    for bucket, blurb in [
        ("writeups", "Folders named `sweep_*` that hold **no captures** — a README "
                     "and figures from an investigation. Kept for the write-up."),
        ("aborted", "Runs that produced no usable capture (opened and stopped, or "
                    "killed before the first condition finished). Kept so the gap "
                    "in the timestamp sequence is explained rather than mysterious."),
        ("troubleshoot", "Closed diagnostic sessions — `console_*` and `isense_*`. "
                         "See `../../STATUS.md` for what each one concluded."),
    ]:
        path = os.path.join(RAW, bucket)
        kids = child_dirs(path)
        if not kids:
            continue
        L += [f"## `{bucket}/`", "", blurb, "",
              f"{len(kids)} folders · {du_mb(path)/1000:.2f} GB", ""]
        L += ["".join(f"- `{k}`\n" for k in kids)]

    # ---- what the pipeline cannot read --------------------------------
    blind = []
    for root, dirs, _ in os.walk(RAW):
        for d in list(dirs):
            p = os.path.join(root, d)
            if glob.glob(os.path.join(p, "*level_*mA_h*ms.csv")):
                info = describe(p)
                if info["naming"] != "cNN":
                    blind.append((os.path.relpath(p, RAW).replace(os.sep, "/"),
                                  info))
                dirs.remove(d)
    if blind:
        L += ["## Not readable by the pipeline", "",
              "Captures named `level_850mA_h400ms.csv` (no `cNN_` prefix). Every "
              "glob in `analyze_raw.py`, `get_cycle.py` and "
              "`plot_drive_trajectory.py` matches `c*_level_*`, so these folders "
              "are on disk but invisible to every stage. Nothing is wrong with the "
              "data — the naming predates the current writer.", "",
              "| folder | captures | grid | size |", "|---|---|---|---|"]
        for rel, d in sorted(blind):
            L.append(f"| `{rel}` | {d['n']} | {grid_str(d)} | {d['mb']:.0f} MB |")
        L.append("")

    return "\n".join(L).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if INDEX.md is out of date")
    a = ap.parse_args()
    text = build()
    if a.check:
        cur = (open(INDEX, encoding="utf-8").read()
               if os.path.exists(INDEX) else "")
        if cur != text:
            print("INDEX.md is STALE — run: python analysis/make_index.py")
            return 1
        print("INDEX.md up to date")
        return 0
    with open(INDEX, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"  -> {os.path.relpath(INDEX, os.path.join(_HERE, '..'))} "
          f"({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
